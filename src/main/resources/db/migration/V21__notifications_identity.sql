-- notifications.id now comes from the table itself (an identity column) instead of notifications_seq.
-- A sequence hands Hibernate ids 50 at a time, so one notice in fifty cost an extra query to fetch the
-- next block; with identity, every change that writes a notice runs the same statements every time.
-- The ids already used are kept: the identity carries on after the highest one.

alter table notifications alter column id add generated by default as identity;
select setval(pg_get_serial_sequence('notifications', 'id'), coalesce((select max(id) from notifications), 0) + 1, false);
drop sequence notifications_seq;
